// Popup menus (one open at a time)
// ---------------------------------------------------------------------------------------------
let current = null;

export function closeMenu() {
  if (!current) return;
  current.menu.hidden = true;
  current.anchor.setAttribute("aria-expanded", "false");
  current = null;
}

export function openMenu(menu, anchor, { align = "right" } = {}) {
  closeMenu();
  menu.hidden = false;
  const r = anchor.getBoundingClientRect();
  const w = menu.offsetWidth;
  const hgt = menu.offsetHeight;
  let left = align === "right" ? r.right - w : r.left;
  left = Math.max(8, Math.min(left, window.innerWidth - w - 8));
  let top = r.bottom + 8;
  if (top + hgt > window.innerHeight - 8) top = Math.max(8, r.top - hgt - 8);
  menu.style.left = `${left}px`;
  menu.style.top = `${top}px`;
  menu.style.setProperty("--origin", align === "right" ? "top right" : "top left");
  anchor.setAttribute("aria-expanded", "true");
  current = { menu, anchor };
}

export function toggleMenu(menu, anchor, opts) {
  if (current && current.menu === menu) closeMenu();
  else openMenu(menu, anchor, opts);
}

export const menuIsOpen = () => !!current;

document.addEventListener(
  "pointerdown",
  (e) => {
    if (current && !current.menu.contains(e.target) && !current.anchor.contains(e.target)) closeMenu();
  },
  true,
);
document.addEventListener("keydown", (e) => {
  if (e.key === "Escape" && current) {
    e.preventDefault(); // tells other Escape handlers (sidebar) that this press was consumed
    const { anchor } = current;
    closeMenu();
    anchor.focus();
  }
});
window.addEventListener("resize", closeMenu);
window.addEventListener("blur", closeMenu);

