// Favicons: tried in order, the first that loads wins; a letter tile is the last resort.
// ---------------------------------------------------------------------------------------------
export function faviconSources(pageUrl) {
  const u = new URL(pageUrl);
  return [
    `https://www.google.com/s2/favicons?sz=128&domain_url=${encodeURIComponent(pageUrl)}`,
    `https://icons.duckduckgo.com/ip3/${u.hostname}.ico`,
    `${u.origin}/favicon.ico`,
  ];
}

export function favicon(pageUrl, label = "") {
  const wrap = h("span", { class: "fav" });
  let sources = [];
  let name = label;
  try {
    sources = faviconSources(pageUrl);
    name ||= new URL(pageUrl).hostname.replace(/^www\./, "");
  } catch {
    /* invalid URL: letter fallback below */
  }
  const letter = () => wrap.replaceChildren(h("span", { class: "fav-letter", text: (name || "?").charAt(0).toUpperCase() }));
  if (!sources.length) {
    letter();
    return wrap;
  }
  let i = 0;
  const img = new Image();
  img.alt = "";
  img.draggable = false;
  img.decoding = "async";
  img.referrerPolicy = "no-referrer";
  img.addEventListener("error", () => {
    i += 1;
    if (i < sources.length) img.src = sources[i];
    else letter();
  });
  img.src = sources[0];
  wrap.append(img);
  return wrap;
}

